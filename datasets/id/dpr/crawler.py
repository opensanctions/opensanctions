# This is above the chamber's 580 seats while pagination remains supported in
# case a legislature contains enough mid-term replacements to exceed it.
PAGE_SIZE = 1000

# The frontend signs every GraphQL request with a static token and a hardcoded HMAC
# secret, both read from the site's axios interceptor. If the endpoint starts
# returning 401/403, they have likely rotated: re-extract by grepping the site's JS
# bundles (/_next/static/chunks/*.js) for "x-api-signature".
API_TOKEN = "48a07687-2a14-4647-9d42-23d7f8ebfa45"
SIGNING_SECRET = "LfmqpWYMaEuQA42LcDvmgbBgG4NDmZp73yr8G8pZ"

# The roster query, a trimmed subset of the site's own getDaftarRiwayatAnggota
# operation (root field, variable input types and enum columns taken verbatim from
# the captured request; committee/photo fields we don't map are omitted).
ROSTER_QUERY = """
query getDaftarRiwayatAnggota(
  $page: Int
  $first: Int!
  $where: QueryGetDaftarRiwayatAnggotaWhereWhereConditions
  $wherePeriode: QueryGetDaftarRiwayatAnggotaWherePeriodeWhereHasConditions
  $orderBy: [QueryGetDaftarRiwayatAnggotaOrderByRelationOrderByClause!]
) {
  getDaftarRiwayatAnggota(
    page: $page
    first: $first
    where: $where
    wherePeriode: $wherePeriode
    orderBy: $orderBy
  ) {
    paginatorInfo { total currentPage lastPage hasMorePages perPage }
    data {
      idPeriode
      noAnggota
      idAnggota
      dapil { id dapil }
      anggota { nama id photofileLink }
      riwayatFraksi { idFraksi fraksi { id fraksi singkatan } }
    }
  }
}
""".strip()

MEMBER_URL = (
    "https://www.dpr.go.id/en/tentang-dpr/informasi-anggota-dewan/detail-anggota/%s-%s"
)


def member_url(name: str, member_id: str) -> str:
    """Build the member detail URL using the slug format generated by the site."""
    return MEMBER_URL % (re.sub(r"[^A-Za-z0-9]+", "-", name), member_id)


def sign_request(method: str, body: bytes) -> dict[str, str]:
    """Build the signing headers required by the /gql endpoint."""
    now = datetime.now(UTC)
    request_at = f"{now:%Y-%m-%dT%H:%M:%S}.{now.microsecond // 1000:03d}Z"
    request_id = str(uuid.uuid4())
    request_body = hashlib.sha256(body).hexdigest()
    message = f"{method.upper()}:{request_body}:{request_at}:{request_id}"
    digest = hmac.new(
        SIGNING_SECRET.encode("utf-8"), message.encode("utf-8"), hashlib.sha256
    ).hexdigest()
    signature = b64encode(digest.encode("utf-8")).decode("utf-8")
    return {
        "x-api-token": API_TOKEN,
        "x-request-at": request_at,
        "x-request-id": request_id,
        "x-request-body": request_body,
        "x-api-signature": signature,
    }


def fetch_page(
    context: Context,
    period_id: int,
    page: int,
    *,
    in_office_only: bool,
    page_size: int = PAGE_SIZE,
) -> dict[str, Any]:
    """Fetch one page of a legislature's roster from the GraphQL endpoint."""
    variables: dict[str, Any] = {
        "page": page,
        "first": page_size,
        "wherePeriode": {"column": "ID", "operator": "EQ", "value": period_id},
        "orderBy": [{"column": "NO_ANGGOTA", "order": "ASC"}],
    }
    if in_office_only:
        # Exclude members replaced mid-term (Pergantian Antar Waktu) from the
        # current roster. Old terms intentionally include both serving and
        # finished records so that every person who served is represented.
        variables["where"] = {
            "column": "STATUS_OFF",
            "operator": "EQ",
            "value": "Dalam masa jabatan",  # "in office"
        }

    payload = {"query": ROSTER_QUERY, "variables": variables}
    body = orjson.dumps(payload)
    headers = {
        "Content-Type": "application/json",
        "Accept": "application/json",
        **sign_request("POST", body),
    }
    result = zyte_api.fetch(
        context,
        ZyteAPIRequest(
            url=context.data_url,
            method="POST",
            body=body,
            headers=headers,
            geolocation="id",
        ),
        # Signatures are timestamped and single-use, so a signed request must not
        # be replayed from cache.
        cache_days=None,
    )
    data = orjson.loads(result.response_text)
    if "errors" in data:
        raise RuntimeError(
            f"GraphQL errors for legislature {period_id}, page {page}: {data['errors']}"
        )
    roster = data["data"]["getDaftarRiwayatAnggota"]
    assert isinstance(roster, dict), roster
    return roster


def fetch_roster(
    context: Context, period_id: int, *, in_office_only: bool
) -> list[dict[str, Any]]:
    """Fetch and completeness-check all pages for one legislature."""
    members: list[dict[str, Any]] = []
    expected_total: int | None = None
    for page in count(start=1):
        roster = fetch_page(context, period_id, page, in_office_only=in_office_only)
        paginator = roster["paginatorInfo"]
        if expected_total is None:
            expected_total = paginator["total"]
        else:
            assert paginator["total"] == expected_total, paginator

        page_members = roster["data"]
        assert isinstance(page_members, list), page_members
        members.extend(page_members)
        if not paginator["hasMorePages"]:
            break

    assert expected_total is not None
    assert len(members) == expected_total, (period_id, len(members), expected_total)

    # Some historical roster rows point to member records which have since been
    # removed from the site's anggota table. idAnggota remains, but without the
    # joined object the API provides no name and we cannot create a valid Person.
    orphaned = [member for member in members if member["anggota"] is None]
    if orphaned:
        context.log.warning(
            "Skipping roster records with missing member details",
            period_id=period_id,
            records=len(orphaned),
            id_anggota=[member["idAnggota"] for member in orphaned[:10]],
        )
    usable_members = [member for member in members if member["anggota"] is not None]
    context.log.info(
        "Fetched legislature roster",
        period_id=period_id,
        records=len(members),
        usable_members=len(usable_members),
    )
    return usable_members


def check_for_new_legislature(context: Context) -> None:
    """Fail visibly when the DPR API starts publishing the next legislature."""
    next_period_id = PERIODE_ID + 1
    roster = fetch_page(
        context,
        next_period_id,
        1,
        # Do not alert merely because the site pre-populates an upcoming term;
        # alert once it marks members of that term as serving.
        in_office_only=True,
        page_size=1,
    )
    total = roster["paginatorInfo"]["total"]
    if total:
        raise RuntimeError(
            f"DPR legislature period {next_period_id} is now available ({total} "
            "serving member records). Update PERIODE_ID and LEGISLATURES with its "
            "dates."
        )


def crawl_member(
    context: Context,
    member: dict[str, Any],
    position: Entity,
    categorisation: PositionCategorisation,
    period_id: int,
    period_start: str,
    period_end: str,
) -> None:
    assert member["idPeriode"] == period_id, member
    member_data = member["anggota"]
    assert member_data is not None, member
    member_id = str(member_data["id"])

    person = context.make("Person")
    person.id = context.make_slug(member_id)

    raw_name = member_data["nama"]
    clean_name = h.strip_name_titles(context, raw_name)
    person.add(
        "name",
        clean_name,
        lang="ind",
        original_value=raw_name if clean_name != raw_name else None,
    )
    # DPR members must be Indonesian citizens (Law No. 7 of 2017 on General
    # Elections, Article 240 paragraph (1)). https://peraturan.bpk.go.id/Details/37644
    person.add("citizenship", "id")
    faction_history = member["riwayatFraksi"]
    if faction_history is not None and faction_history["fraksi"] is not None:
        person.add("political", faction_history["fraksi"]["fraksi"], lang="ind")
    person.add("sourceUrl", member_url(raw_name, member_id))

    occupancy = h.make_occupancy(
        context,
        person,
        position,
        categorisation=categorisation,
        period_start=period_start,
        period_end=period_end,
        # The live-period query is explicitly filtered to serving members.
        no_end_implies_current=period_id == PERIODE_ID,
    )
    if occupancy is None:
        return
    constituency = member["dapil"]
    if constituency is not None:
        occupancy.add("constituency", constituency["dapil"], lang="ind")
    context.emit(person)
    context.emit(occupancy)


def crawl(context: Context) -> None:
    first_period_id = min(LEGISLATURES)
    assert set(LEGISLATURES) == set(range(first_period_id, PERIODE_ID + 1)), (
        LEGISLATURES
    )
    check_for_new_legislature(context)

    position = h.make_position(
        context,
        name="Member of the People's Representative Council of Indonesia",
        country="id",
        topics=["gov.national", "gov.legislative"],
        wikidata_id="Q21328632",
        lang="eng",
    )
    categorisation = categorise(context, position)
    if not categorisation.is_pep:
        return
    context.emit(position)

    for period_id, (period_start, period_end) in LEGISLATURES.items():
        if period_end < h.earliest_term_start(categorisation.topics):
            context.log.info(
                "Skipping legislature outside PEP coverage",
                period_id=period_id,
                period_end=period_end,
            )
            continue
        members = fetch_roster(
            context,
            period_id,
            in_office_only=period_id == PERIODE_ID,
        )
        for member in members:
            crawl_member(
                context,
                member,
                position,
                categorisation,
                period_id,
                period_start,
                period_end,
            )
